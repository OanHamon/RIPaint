VARIANTS = [
    Variant(COLORS, "couleurs", "COLOR", COLOR_TEAMS),
    Variant("countries", "pays", "COUNTRY", COUNTRIES, nicknames=False),
    Variant("fruits", "fruits", "FRUIT", FRUITS, nicknames=False),
    Variant("animals", "animaux", "ANIMAL", ANIMALS, nicknames=False),
    Variant("planets", "planètes", "PLANET", PLANETS, nicknames=False),
]

BY_KEY = {v.key: v for v in VARIANTS}
BY_NAME = {c.name: c for v in VARIANTS for c in v.competitors}
# Choix proposés dans l'interface : (valeur du réglage, libellé)
CHOICES = [(v.key, v.label) for v in VARIANTS] + [(RANDOM, "aléatoire")]


def resolve(settings, seed: int = 0) -> Variant:
    """Variante de la partie. « random » : tirée selon la seed (générateur à part)."""
    key = getattr(settings, "variant", COLORS)
    if key == RANDOM:
        return random.Random(seed * 2741 + 37).choice(VARIANTS)
    return BY_KEY.get(key, BY_KEY[COLORS])


def colors(name: str) -> tuple:
    """(foncée, principale, claire) d'un concurrent."""
    return BY_NAME[name].colors
